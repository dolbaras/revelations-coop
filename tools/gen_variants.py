"""gen_variants.py: tools/variants.json -> native/variants.h (the proxy's list of known exes). Run: python -I tools/gen_variants.py [--check]"""
import json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, 'variants.json')
dst = os.path.join(here, '..', 'native', 'variants.h')
v = json.load(open(src, encoding='utf-8'))['variants']
lines = ['/* GENERATED by tools/gen_variants.py from tools/variants.json: do not edit. The known game exes (lower-case SHA-256). */',
         '#ifndef R1_VARIANTS_H', '#define R1_VARIANTS_H',
         'typedef struct { const char *id; const char *sha256; const char *kind; } r1_variant_t;',
         'static const r1_variant_t r1_variants[] = {']
for x in v:
    lines.append('    {"%s", "%s", "%s"},' % (x['id'], x['sha256'].lower(), x['kind']))
lines += ['};', '#define R1_N_VARIANTS ((int)(sizeof r1_variants / sizeof r1_variants[0]))', '#endif', '']
text = '\n'.join(lines)
if '--check' in sys.argv:
    cur = open(dst, encoding='utf-8').read() if os.path.exists(dst) else ''
    sys.exit(0 if cur == text else 1)
open(dst, 'w', encoding='utf-8', newline='\n').write(text)
print('wrote', dst)
